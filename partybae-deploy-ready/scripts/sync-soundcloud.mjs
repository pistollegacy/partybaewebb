// scripts/sync-soundcloud.mjs
// Verifies PARTYBAE's public SoundCloud catalog and writes src/data/tracks.ts
// Usage: SC_CLIENT_ID=xxx node scripts/sync-soundcloud.mjs

const USER_ID = process.env.SOUNDCLOUD_USER_ID ?? '643183869';
const PERMALINK = 'partybae';
const PAGE_LIMIT = 100;
const MAX_PAGES = 5;
const API_BASE = 'https://api-v2.soundcloud.com';
const CLIENT_ID = process.env.SC_CLIENT_ID;

if (!CLIENT_ID) {
  console.error('✖ SC_CLIENT_ID not set. Set it to run live sync.');
  console.error('   For production: register an app at https://soundcloud.com/you/apps');
  console.error('   For one-off: the public web client_id can be extracted from soundcloud.com assets');
  process.exit(1);
}

function upgradeArtwork(url) {
  if (!url) return null;
  return url.replace(/-large\.(jpg|png)$/i, '-t500x500.$1').replace(/-t\d+x\d+\.(jpg|png)$/i, '-t500x500.$1');
}

function fmtDuration(ms) {
  const totalSec = Math.round(ms / 1000);
  const m = Math.floor(totalSec / 60);
  const s = totalSec % 60;
  return `${m}:${s.toString().padStart(2, '0')}`;
}

async function fetchPage(url) {
  const ctrl = new AbortController();
  const timeout = setTimeout(() => ctrl.abort(), 8000);
  try {
    const res = await fetch(url, {
      headers: { accept: 'application/json' },
      signal: ctrl.signal,
    });
    if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
    return await res.json();
  } finally {
    clearTimeout(timeout);
  }
}

async function fetchAllTracks() {
  const all = [];
  let nextUrl = `${API_BASE}/users/${USER_ID}/tracks?client_id=${CLIENT_ID}&limit=${PAGE_LIMIT}&offset=0`;
  let pages = 0;

  while (nextUrl && pages < MAX_PAGES) {
    console.log(`  Fetching page ${pages + 1}...`);
    const data = await fetchPage(nextUrl);
    const tracks = data.collection ?? [];
    console.log(`    Got ${tracks.length} tracks`);
    all.push(...tracks);
    nextUrl = data.next_href ? `${data.next_href}&client_id=${CLIENT_ID}` : null;
    pages++;
    if (!nextUrl) break;
    await new Promise(r => setTimeout(r, 200));
  }
  return all;
}

function mapTrack(t) {
  return {
    id: t.id,
    title: t.title,
    permalink: t.permalink,
    url: `https://soundcloud.com/${PERMALINK}/${t.permalink}`,
    createdAt: t.created_at,
    durationMs: t.duration ?? 0,
    artwork: upgradeArtwork(t.artwork_url ?? t.user?.avatar_url ?? null),
    genre: t.genre ?? null,
    description: (t.description ?? '').trim(),
  };
}

async function main() {
  console.log('🎵 Syncing PARTYBAE SoundCloud catalog...');
  const raw = await fetchAllTracks();
  const tracks = raw.map(mapTrack).sort((a, b) => +new Date(b.createdAt) - +new Date(a.createdAt));

  // Dedupe by id
  const seen = new Set();
  const uniq = tracks.filter(t => (seen.has(t.id) ? false : (seen.add(t.id), true)));

  console.log(`✅ Total unique tracks: ${uniq.length}`);

  const now = new Date().toISOString();
  const content = `// AUTO-GENERATED by scripts/sync-soundcloud.mjs
// Verified via SoundCloud API on ${now}
// DO NOT EDIT MANUALLY — run 'npm run sync:soundcloud' to update

export interface Track {
  id: number;
  title: string;
  permalink: string;
  url: string;
  createdAt: string;
  durationMs: number;
  artwork: string | null;
  genre: string | null;
  description: string;
}

export const TRACKS: Track[] = ${JSON.stringify(uniq, null, 2)};

export const CATALOG_META = {
  userId: ${USER_ID},
  permalink: '${PERMALINK}',
  profileUrl: 'https://soundcloud.com/${PERMALINK}',
  verifiedAt: '${now}',
  trackCount: ${uniq.length},
} as const;
`;

  const fs = await import('fs');
  const path = await import('path');
  const outPath = path.resolve('src/data/tracks.ts');
  fs.writeFileSync(outPath, content);
  console.log(`📝 Written to ${outPath}`);
}

main().catch(err => {
  console.error('✖ Sync failed:', err);
  process.exit(1);
});